    enum Language: String, Sendable {
        case zhCN = "zh-CN"
        case enUS = "en-US"

        static func parse(_ raw: String) -> Language {
            let lower = raw.lowercased()
            if lower.hasPrefix("en") { return .enUS }
            return .zhCN
        }
    }

    static func t(_ key: String, language: String) -> String {
        t(key, lang: Language.parse(language))
    }

    static func t(_ key: String, lang: Language) -> String {
        let table = lang == .enUS ? enUS : zhCN
        return table[key] ?? zhCN[key] ?? enUS[key] ?? key
    }

